// ----- Carpetas: ícono y color propio de cada una -----

const FOLDER_LOOK: Record<string, { icon: IconName; hue: number }> = {
  "Notas rápidas": { icon: "zap", hue: 32 },
  Diario: { icon: "book", hue: 275 },
  Escuela: { icon: "cap", hue: 212 },
  Trabajo: { icon: "briefcase", hue: 152 },
  Hobbys: { icon: "palette", hue: 335 },
};

/** Las carpetas propias reciben un color fijo según su nombre. */
export function folderLook(name: string): { icon: IconName; hue: number } {
  const known = FOLDER_LOOK[name];
  if (known) return known;
  let h = 0;
  for (const c of name) h = (h * 31 + c.charCodeAt(0)) % 360;
  return { icon: "folder", hue: h };
}

/** Etiqueta de carpeta con su color pastel (tarjetas y barra de la nota). */
export function FolderTag({ name, short = false }: { name: string; short?: boolean }) {
  const { icon, hue } = folderLook(name);
  return (
    <span className="ftag" style={{ "--h": hue } as CSSProperties} title={name}>
      <Icon name={icon} size={13} />
      {!short && <span className="ftag-label">{name}</span>}
    </span>
  );
}
